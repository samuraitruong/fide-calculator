import React from 'react';
import { act, fireEvent, render, screen } from '@testing-library/react';
import ProfileModal from '../ProfileModal';
import { refreshFidePlayer } from '@fide-calculator/shared';
jest.mock('../../../../../packages/shared/src', () => ({ refreshFidePlayer: jest.fn() }));
const save = jest.fn();
jest.mock('@/contexts/AuthContext', () => ({ useAuth: () => ({ user: null, activeProfile: null, loading: false }) }));
jest.mock('@/hooks/useLocalStorage', () => ({ useLocalStorage: () => ({ updateProfile: save }) }));
jest.mock('../FideSearchInput', () => function MockFideSearchInput({ value, onChange }: { value: string; onChange: (value: string) => void }) { return <input aria-label="Name" value={value} onChange={e => onChange(e.target.value)} />; });
const profile = { id: 'p1', name: 'Doe, Jane', fideId: '42', standardRating: 1800, rapidRating: 1801, blitzRating: 1802, isLocal: true };
const player = { name: 'Doe, Jane', fideId: '42', standard: '2100', rapid: '2200', blitz: '-', title: 'FM', federation: 'AUS', birthYear: '1990' };
const props = { open: true, onClose: jest.fn(), onSuccess: jest.fn(), isLocalMode: true, localProfile: profile };
beforeEach(() => jest.clearAllMocks());
it('disables edits and save while refreshing, fills the draft and saves only explicitly', async () => {
  let resolve!: (value: typeof player) => void;
  (refreshFidePlayer as jest.Mock).mockReturnValue(new Promise<typeof player>(r => { resolve = r; }));
  render(<ProfileModal {...props} />);
  fireEvent.click(screen.getByText('Refresh FIDE data'));
  expect(screen.getByRole('button', { name: /Refreshing/ })).toBeDisabled();
  expect(screen.getByRole('button', { name: /Update Profile/ })).toBeDisabled();
  expect(screen.getByLabelText('Standard Rating')).toBeDisabled();
  await act(async () => resolve(player));
  expect(screen.getByLabelText('Standard Rating')).toHaveValue(2100);
  expect(screen.getByLabelText('Blitz Rating')).toHaveValue(1802);
  expect(save).not.toHaveBeenCalled();
  expect(screen.getByText(/Save to apply/)).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: /Update Profile/ }));
  expect(save).toHaveBeenCalledWith(expect.objectContaining({ standardRating: 2100, title: 'FM', federation: 'AUS', birthYear: 1990 }));
});
it('preserves edited draft on refresh failure', async () => {
  (refreshFidePlayer as jest.Mock).mockRejectedValue(new Error('Offline'));
  render(<ProfileModal {...props} />);
  fireEvent.change(screen.getByLabelText('Standard Rating'), { target: { value: '1950' } });
  await act(async () => fireEvent.click(screen.getByText('Refresh FIDE data')));
  expect(screen.getByLabelText('Standard Rating')).toHaveValue(1950);
  expect(screen.getByText('Offline')).toBeInTheDocument();
});
it('ignores a late result after the modal closes and reopens with another profile', async () => {
  let resolve!: (value: typeof player) => void;
  (refreshFidePlayer as jest.Mock).mockReturnValue(new Promise<typeof player>(r => { resolve = r; }));
  const view = render(<ProfileModal {...props} />);
  fireEvent.click(screen.getByText('Refresh FIDE data'));
  view.rerender(<ProfileModal {...props} open={false} />);
  view.rerender(<ProfileModal {...props} localProfile={{ ...profile, id: 'p2', name: 'Other', fideId: '88', standardRating: 1700 }} />);
  await act(async () => resolve(player));
  expect(screen.getByLabelText('Name')).toHaveValue('Other');
  expect(screen.getByLabelText('Standard Rating')).toHaveValue(1700);
});
it('ignores a late refresh when the same profile is rehydrated with a different player identity', async () => {
  let resolve!: (value: typeof player) => void;
  (refreshFidePlayer as jest.Mock).mockReturnValue(new Promise<typeof player>(r => { resolve = r; }));
  const view = render(<ProfileModal {...props} />);
  fireEvent.click(screen.getByText('Refresh FIDE data'));
  view.rerender(<ProfileModal {...props} localProfile={{ ...profile, name: 'Other', fideId: '88', standardRating: 1700 }} />);
  await act(async () => resolve(player));
  expect(screen.getByLabelText('Name')).toHaveValue('Other');
  expect(screen.getByLabelText('FIDE ID')).toHaveValue('88');
  expect(screen.getByLabelText('Standard Rating')).toHaveValue(1700);
});
